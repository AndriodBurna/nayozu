function json(data, status = 200) {
  return new Response(JSON.stringify(data, null, 2), {
    status,
    headers: {
      "Content-Type": "application/json",
      "Access-Control-Allow-Origin": "*",
      "Cache-Control": "public, max-age=300",
    },
  });
}

function rewriteRequest(request, newPath) {
  const u = new URL(request.url);
  u.pathname = newPath;
  return new Request(u.toString(), { method: request.method, headers: request.headers });
}

// Stream hosts frequently block datacenter/residential IPs with 403/500 even
// though the URL is freshly minted and valid. Clients that just take
// streams[0].url end up with a dead link and no way to tell.
//
// With ?verify=1 we probe each stream (sending the referer the provider
// returned, which several CDNs require) and drop the dead ones, promoting the
// first survivor to isActive. This is opt-in because it costs an extra
// round-trip per stream.
async function verifyStreams(payload) {
  const streams = Array.isArray(payload?.streams) ? payload.streams : [];
  if (!streams.length) return payload;

  const checked = await Promise.all(
    streams.map(async (stream) => {
      const url = typeof stream === "string" ? stream : stream?.url;
      if (!url || !/^https?:\/\//i.test(url)) return { ...stream, _verified: false };

      const headers = {
        "User-Agent":
          stream.userAgent ||
          "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/149.0.0.0 Safari/537.36",
        Accept: "*/*",
      };
      // Many CDNs (flixcloud, megaplay, animegg...) reject requests without a
      // matching Referer. The provider already worked out the right origin.
      const referer = stream.referer || stream.headers?.Referer || stream.headers?.referer;
      if (referer) headers.Referer = referer;
      if (stream.headers && typeof stream.headers === "object") {
        for (const [k, v] of Object.entries(stream.headers)) {
          if (typeof v === "string" && !headers[k]) headers[k] = v;
        }
      }

      try {
        // HEAD is cheap, but some CDNs 405 on it — fall back to a ranged GET.
        let res = await fetch(url, { method: "HEAD", headers });
        if (res.status === 405 || res.status === 501) {
          res = await fetch(url, { headers: { ...headers, Range: "bytes=0-1023" } });
        }
        const alive = res.status >= 200 && res.status < 400;
        return { ...stream, _verified: alive, _status: res.status };
      } catch (err) {
        return { ...stream, _verified: false, _status: 0, _error: err.message };
      }
    })
  );

  const alive = checked.filter((s) => s._verified);
  const finalStreams = alive.length ? alive : checked;
  return {
    ...payload,
    streams: finalStreams.map((s, i) => ({ ...s, isActive: i === 0 })),
    _verify: {
      checked: checked.length,
      alive: alive.length,
      dead: checked.length - alive.length,
    },
  };
}

const watchInflight = new Map();
const SIGNED_STREAM_WATCH_TTL = 60_000;

function wantsVerify(request) {
  try {
    return new URL(request.url).searchParams.get("verify") === "1";
  } catch {
    return false;
  }
}

async function cachedWatch(cacheKey, handlerFn, ttl = WATCH_TTL, verify = false) {
  // Verification result is per-request state, never cached — a URL that was
  // alive a minute ago may be blocked now, and vice versa.
  if (verify) {
    const response = await handlerFn();
    if (response.status !== 200) return response;
    const data = await response.clone().json();
    return json(await verifyStreams(data));
  }

  const entry = await getAsync(cacheKey);
  if (entry && isFresh(entry)) return json(entry.data);

  if (watchInflight.has(cacheKey)) {
    await watchInflight.get(cacheKey).catch(() => {});
    const warm = await getAsync(cacheKey);
    if (warm && isFresh(warm)) return json(warm.data);
    return handlerFn();
  }

  const promise = (async () => {
    const response = await handlerFn();
    if (response.status === 200) {
      try {
        const data = await response.clone().json();
        await setAsync(cacheKey, data, ttl);
      } catch {}
    }
    return response;
  })();

  watchInflight.set(cacheKey, promise);
  try   { return await promise; }
  finally { watchInflight.delete(cacheKey); }
}

